"""Writes BUTTONS.md: what sends each joystick button, for mapping by hand. PC only, not copied to the board
(code that is never run still costs RAM there): `python3 make_buttons.py > BUTTONS.md`."""
from buttonmap import BUTTON, DEVICE, PLAIN_KEYS, SIZE, UNIT_KEYS, shifted

KNOB = {   # base name -> control; _UP is clockwise, _DN counter-clockwise
    "ALT_100": "ALT/HDG outer, slow", "ALT_1000": "ALT/HDG outer, fast", "HDG_1": "ALT/HDG inner, slow",
    "HDG_10": "ALT/HDG inner, fast", "CRS_1": "SHIFT, ALT/HDG outer, slow", "CRS_10": "SHIFT, ALT/HDG outer, fast",
    "BARO": "SHIFT, ALT/HDG inner", "SQK_D2": "SHIFT, FREQ outer, slow", "SQK_D1": "SHIFT, FREQ outer, fast",
    "SQK_D4": "SHIFT, FREQ inner, slow", "SQK_D3": "SHIFT, FREQ inner, fast", "COM_MHZ": "FREQ outer, COM mode",
    "COM_KHZ": "FREQ inner, COM mode", "NAV_MHZ": "FREQ outer, NAV mode", "NAV_KHZ": "FREQ inner, NAV mode",
    "ADF_100": "FREQ outer, ADF mode", "ADF_1": "FREQ inner, ADF mode, slow",
    "ADF_10": "FREQ inner, ADF mode, fast", "PANEL_LT": "SHIFT, FMS outer", "FLOOD_LT": "SHIFT, FMS inner",
}
OTHER = {
    "HDG_SYNC": "ALT/HDG push", "BARO_STD": "SHIFT, ALT/HDG push", "XPDR_MODE": "SHIFT, FREQ push",
    "FREQ_PUSH": "FREQ push (next mode: COM, NAV, ADF)", "CABIN_LT": "SHIFT, FMS push", "PTR": "RANGE push",
    "RANGE_CW": "RANGE turn, clockwise", "RANGE_CCW": "RANGE turn, counter-clockwise",
    "PAN_UP": "RANGE tilt up", "PAN_DN": "RANGE tilt down", "PAN_LEFT": "RANGE tilt left",
    "PAN_RIGHT": "RANGE tilt right", "FMS_CRSR": "FMS push", "FMS_OUTER_CW": "FMS outer, clockwise",
    "FMS_OUTER_CCW": "FMS outer, counter-clockwise", "FMS_INNER_CW": "FMS inner, clockwise",
    "FMS_INNER_CCW": "FMS inner, counter-clockwise",
}


def key_text(k):
    text = {"DIRECT": "D→"}.get(k, k.replace("_SWAP", " ⇆"))
    return text[:-1] + " " + text[-1] if text[-1].isdigit() else text


def control(name):
    if name in OTHER:
        return OTHER[name]
    if name.startswith("S_") and name[2:] in OTHER:
        return "SHIFT, " + OTHER[name[2:]]
    base, _, way = name.rpartition("_")
    if way in ("UP", "DN") and base in KNOB:
        return KNOB[base] + (", clockwise" if way == "UP" else ", counter-clockwise")
    for key in PLAIN_KEYS + UNIT_KEYS:
        if name == key:
            return "key " + key_text(key)
        if name == shifted(key):
            return "SHIFT, key " + key_text(key)
    raise KeyError("no control description for " + name)


def main():
    print("# Avionics Panel rev 1: joystick buttons\n")
    print("Generated by `python3 make_buttons.py > BUTTONS.md`. The panel is two USB joysticks, both named")
    print("\"Avionics Panel\": device 1 (128 buttons) carries everything plus unit 1, device 2 (64 buttons) the")
    print("unit 2 copies, sent while UNIT 2 is selected (SHIFT, HOME). Button numbers as Windows and MobiFlight")
    print("show them (1-based). Every knob detent is a short press, so map it as \"on press\". The numbers are")
    print("frozen from the first build on: new buttons only go at the end.\n")
    print("| Name | Control | Device 1 | Device 2 |")
    print("| --- | --- | --- | --- |")
    for n in DEVICE[1]:
        d2 = BUTTON[2].get(n)
        d2 = "" if d2 is None else f"{d2 + 1} "
        print(f"| {n} | {control(n)} | {BUTTON[1][n] + 1} | {d2}|")
    print(f"\nDevice 1: {len(DEVICE[1])} of {SIZE[1]} buttons. Device 2: {len(DEVICE[2])} of {SIZE[2]}.")


if __name__ == "__main__":
    main()
