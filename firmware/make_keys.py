"""Writes KEYS.md: the shortcut each function sends in keyboard mode (keys.py), for binding in the sim. PC only, not
copied to the board (code that is never run still costs RAM there): `python3 make_keys.py > KEYS.md`."""
from buttonmap import BUTTON, DEVICE
from keys import shortcut
from make_buttons import control

# HID usage IDs (Keyboard/Keypad page) and modifier bits as people name them
KEY_NAMES = {**{0x3A + i: f"F{1 + i}" for i in range(12)}, 0x49: "Insert", 0x4A: "Home", 0x4B: "Page Up",
             0x4E: "Page Down", 0x4F: "Right", 0x50: "Left", 0x51: "Down", 0x52: "Up"}
MODIFIER_NAMES = ((0x01, "Ctrl"), (0x10, "Right Ctrl"), (0x02, "Shift"), (0x20, "Right Shift"), (0x04, "Alt"))


def shortcut_name(mods, key):
    """A shortcut as the docs and the panel page write it, such as Ctrl+Right Shift+Insert"""
    return "+".join([n for bit, n in MODIFIER_NAMES if mods & bit] + [KEY_NAMES[key]])


def owners():
    """{(modifiers, key): the function the shortcut stands for}; SHIFT with a key without an amber legend sends
    the key's, unit 2 unit 1's except for COM and NAV, whose own the name marks"""
    out = {}
    for dev in (1, 2):
        for b, name in enumerate(DEVICE[dev]):
            name = name[2:] if name.startswith("S_") else name
            out.setdefault(shortcut(dev, b), name + (" (unit 2)" if dev == 2 else ""))
    return out


def contains(mods, key, names):
    """The functions whose shortcut is part of this one: the same key with only some of its modifiers. MSFS is
    reported to fire such a binding when this shortcut has none."""
    return [n for (m, k), n in names.items() if k == key and m != mods and not m & ~mods]


def main():
    names = owners()
    print("# Avionics Panel rev 1: keyboard shortcuts\n")
    print("Generated by `python3 make_keys.py > KEYS.md`. The shortcut each function sends in the")
    print("[keyboard mode](../docs/using/keyboard.md). Ctrl, Shift and Alt are the left keys. Unit 2 shows a")
    print("shortcut only where it differs. Contains names the functions whose shortcut is part of the row's: the")
    print("same key with only some of its modifiers. If you bind one of them, bind the row too")
    print("([why](../docs/using/keyboard.md#binding)). The shortcuts are frozen: new functions get new ones.\n")
    print("| Name | Control | Shortcut | Unit 2 | Contains |")
    print("| --- | --- | --- | --- | --- |")
    for n in DEVICE[1]:
        one, two = shortcut(1, BUTTON[1][n]), BUTTON[2].get(n)
        two = None if two is None or shortcut(2, two) == one else shortcut(2, two)
        parts = ", ".join(contains(*one, names))
        if two and contains(*two, names):
            parts = "; ".join(p for p in (parts, "unit 2: " + ", ".join(contains(*two, names))) if p)
        cells = (n, control(n), shortcut_name(*one), shortcut_name(*two) if two else "", parts)
        print("|" + "|".join(f" {c} " if c else " " for c in cells) + "|")
    print(f"\n{len(names)} shortcuts for the {len(DEVICE[1])} buttons of device 1 and {len(DEVICE[2])} of "
          "device 2.")


if __name__ == "__main__":
    main()
